RECOVER_JOBS = """
CREATE FUNCTION app.recover_expired_jobs()
RETURNS TABLE (job_id uuid, owner_id uuid, kind text, status text)
LANGUAGE sql VOLATILE SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $fn$
  UPDATE app.jobs AS j
  SET status = CASE WHEN j.cancel_requested THEN 'cancelled'
                    WHEN j.attempts < j.max_attempts THEN 'queued'
                    ELSE 'failed' END,
      error_code = 'lease_expired',
      run_after = now() + make_interval(secs => 5 * j.attempts),
      lease_expires_at = NULL,
      locked_by = NULL,
      finished_at = CASE WHEN j.cancel_requested OR j.attempts >= j.max_attempts
                         THEN now() END
  WHERE j.id IN (
    SELECT e.id FROM app.jobs AS e
    WHERE e.status = 'running' AND e.lease_expires_at < now()
    FOR UPDATE SKIP LOCKED
  )
  RETURNING j.id, j.owner_id, j.kind::text, j.status::text
$fn$
"""

RELEASE_RESERVATIONS = """
CREATE FUNCTION app.release_expired_reservations()
RETURNS integer
LANGUAGE sql VOLATILE SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $fn$
  -- DELETE locks each row; a concurrent settle or sweep then finds it gone,
  -- so every reservation is returned exactly once.
  WITH gone AS (
    DELETE FROM app.budget_reservations AS b
    WHERE b.expires_at < now()
    RETURNING b.owner_id, b.day, b.amount_usd
  ),
  by_user AS (
    UPDATE app.spend_user AS s
    SET reserved_usd = greatest(s.reserved_usd - g.total, 0)
    FROM (SELECT owner_id, day, sum(amount_usd) AS total FROM gone GROUP BY owner_id, day) AS g
    WHERE s.owner_id = g.owner_id AND s.day = g.day
    RETURNING 1
  ),
  by_day AS (
    UPDATE app.spend_global AS s
    SET reserved_usd = greatest(s.reserved_usd - g.total, 0)
    FROM (SELECT day, sum(amount_usd) AS total FROM gone GROUP BY day) AS g
    WHERE s.day = g.day
    RETURNING 1
  )
  SELECT count(*)::integer FROM gone
$fn$
"""
